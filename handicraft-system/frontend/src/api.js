import axios from 'axios'
export const api=axios.create({baseURL:'/api',timeout:10000})
export const login=(data)=>api.post('/auth/login',data)
export const getWorks=(params={})=>api.get('/works',{params})
export const getFeatured=()=>api.get('/works/featured')
export const getRequests=(params={})=>api.get('/requests',{params})
export const createRequest=(data)=>api.post('/requests',data)
export const getQuotes=(requestId)=>api.get('/quotes',{params:{requestId}})
export const createQuote=(data)=>api.post('/quotes',data)
export const createOrderFromQuote=(id)=>api.post('/orders/from-quote/'+id)
export const getOrders=(params={})=>api.get('/orders',{params})
export const updateProgress=(id,data)=>api.put('/orders/'+id+'/progress',data)
export const completeOrder=(id)=>api.put('/orders/'+id+'/complete')
export const getDashboard=()=>api.get('/dashboard')
